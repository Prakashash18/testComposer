create or replace function public.get_available_presentation_slots()
returns table (
  id bigint,
  start_at timestamptz,
  end_at timestamptz
)
language sql
security definer
set search_path = public, pg_temp
as $$
  select s.id, s.start_at, s.end_at
  from public.presentation_slots s
  where s.is_active = true
    and not exists (
      select 1
      from public.presentation_bookings b
      where b.slot_id = s.id
    )
  order by s.start_at;
$$;

-- Remove the older 3-argument function if this project was set up previously.
drop function if exists public.book_presentation_slot(bigint, smallint, text);

create or replace function public.book_presentation_slot(
  p_slot_id bigint,
  p_group_no smallint,
  p_student_name text,
  p_student_email text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_name text := trim(p_student_name);
  v_email text := lower(trim(p_student_email));
  v_start timestamptz;
  v_end timestamptz;
  v_booking_id uuid;
begin
  if p_group_no is null or p_group_no < 1 or p_group_no > 11 then
    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_GROUP',
      'message', 'Group number must be between 1 and 11.'
    );
  end if;

  if v_name is null or char_length(v_name) < 2 or char_length(v_name) > 120 then
    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_NAME',
      'message', 'Please enter your name.'
    );
  end if;

  if v_email is null
     or char_length(v_email) < 5
     or char_length(v_email) > 254
     or position('@' in v_email) <= 1
     or position('.' in split_part(v_email, '@', 2)) = 0 then
    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_EMAIL',
      'message', 'Please enter a valid email address.'
    );
  end if;

  select s.start_at, s.end_at
  into v_start, v_end
  from public.presentation_slots s
  where s.id = p_slot_id
    and s.is_active = true;

  if not found then
    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_SLOT',
      'message', 'This slot is not available.'
    );
  end if;

  begin
    insert into public.presentation_bookings (slot_id, group_no, student_name, student_email)
    values (p_slot_id, p_group_no, v_name, v_email)
    returning id into v_booking_id;
  exception
    when unique_violation then
      if exists (
        select 1
        from public.presentation_bookings
        where group_no = p_group_no
      ) then
        return jsonb_build_object(
          'ok', false,
          'code', 'GROUP_ALREADY_BOOKED',
          'message', 'Your group has already booked a presentation slot.'
        );
      else
        return jsonb_build_object(
          'ok', false,
          'code', 'SLOT_TAKEN',
          'message', 'That slot was just taken. Please choose another slot.'
        );
      end if;
  end;

  return jsonb_build_object(
    'ok', true,
    'code', 'BOOKED',
    'message', 'Presentation slot booked successfully.',
    'booking_id', v_booking_id,
    'group_no', p_group_no,
    'student_name', v_name,
    'start_at', v_start,
    'end_at', v_end
  );
end;
$$;

-- Functions are the only public database API surface.
revoke all on function public.get_available_presentation_slots() from public;
revoke all on function public.book_presentation_slot(bigint, smallint, text, text) from public;

grant execute on function public.get_available_presentation_slots() to anon, authenticated;
grant execute on function public.book_presentation_slot(bigint, smallint, text, text) to anon, authenticated;

